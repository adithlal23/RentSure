const PDFDocument = require("pdfkit");
const { pool } = require("../config/db");
const Inspection = require("../models/Inspection");

// Reusable PDF header
const addHeader = (doc, title) => {
  doc.fontSize(22).font("Helvetica-Bold").text("RentSure", { align: "center" });
  doc.moveDown(0.3);
  doc.fontSize(15).font("Helvetica-Bold").text(title, { align: "center" });
  doc.moveDown();
  doc.moveTo(50, doc.y).lineTo(545, doc.y).stroke();
  doc.moveDown();
};

const addField = (doc, label, value) => {
  doc.font("Helvetica-Bold").fontSize(10).text(`${label}: `, { continued: true });
  doc.font("Helvetica").text(String(value ?? "Not provided"));
  doc.moveDown(0.4);
};

// GENERATE INSPECTION REPORT
const generateInspectionReport = async (req, res) => {
  try {
    const inspection = await Inspection.findById(req.params.id).lean();

    if (!inspection) {
      return res.status(404).json({
        success: false,
        message: "Inspection report not found."
      });
    }

    // Verify landlord owns the property linked to this inspection
    const [leases] = await pool.query(
      `SELECT p.property_name, p.address, p.city,
              u.full_name AS tenant_name, l.lease_id
       FROM leases l
       JOIN properties p ON l.property_id = p.property_id
       JOIN users u ON l.tenant_id = u.user_id
       WHERE l.lease_id = ? AND p.landlord_id = ?`,
      [inspection.leaseId, req.user.userId]
    );

    if (leases.length === 0) {
      return res.status(403).json({
        success: false,
        message: "You are not authorized to access this inspection."
      });
    }

    const details = leases[0];

    res.setHeader("Content-Type", "application/pdf");
    res.setHeader(
      "Content-Disposition",
      'attachment; filename="RentSure-Inspection-Report.pdf"'
    );

    const doc = new PDFDocument({ margin: 50 });
    doc.pipe(res);

    addHeader(doc, "Property Inspection Report");

    addField(doc, "Property", details.property_name);
    addField(doc, "Address", `${details.address}, ${details.city}`);
    addField(doc, "Tenant", details.tenant_name);
    addField(doc, "Lease ID", inspection.leaseId);
    addField(doc, "Inspection Type", inspection.inspectionType);
    addField(doc, "Inspection Date", new Date(inspection.inspectionDate).toLocaleString());
    addField(doc, "Tenant Acknowledged", inspection.tenantAcknowledged ? "Yes" : "No");
    addField(doc, "Landlord Acknowledged", inspection.landlordAcknowledged ? "Yes" : "No");

    doc.moveDown();
    doc.fontSize(14).font("Helvetica-Bold").text("Room Condition Details");
    doc.moveDown();

    for (const room of inspection.rooms || []) {
      if (doc.y > 700) doc.addPage();

      doc.fontSize(11).font("Helvetica-Bold").text(room.roomName);
      addField(doc, "Condition", room.condition);
      addField(doc, "Notes", room.notes || "No notes");

      if (room.evidence?.length) {
        doc.font("Helvetica-Bold").text("Evidence:");
        for (const item of room.evidence) {
          doc.font("Helvetica").fontSize(9)
            .text(`Image: ${item.imageUrl || "No image URL"}`);
          if (item.description) {
            doc.text(`Description: ${item.description}`);
          }
        }
        doc.moveDown();
      }
    }

    doc.moveDown();
    doc.fontSize(9).text("Generated by RentSure Property Management System.", {
      align: "center"
    });

    doc.end();

  } catch (error) {
    console.error("Inspection PDF error:", error.message);
    if (!res.headersSent) {
      res.status(500).json({
        success: false,
        message: "Could not generate inspection PDF."
      });
    } else {
      res.destroy(error);
    }
  }
};


// GENERATE DEPOSIT SETTLEMENT REPORT
const generateDepositReport = async (req, res) => {
  try {
    const [deposits] = await pool.query(
      `SELECT
         d.*,
         p.property_name,
         p.address,
         p.city,
         u.full_name AS tenant_name,
         l.start_date,
         l.end_date
       FROM security_deposits d
       JOIN leases l ON d.lease_id = l.lease_id
       JOIN properties p ON l.property_id = p.property_id
       JOIN users u ON l.tenant_id = u.user_id
       WHERE d.deposit_id = ? AND p.landlord_id = ?`,
      [req.params.id, req.user.userId]
    );

    if (deposits.length === 0) {
      return res.status(404).json({
        success: false,
        message: "Deposit record not found."
      });
    }

    const deposit = deposits[0];

    res.setHeader("Content-Type", "application/pdf");
    res.setHeader(
      "Content-Disposition",
      'attachment; filename="RentSure-Deposit-Settlement.pdf"'
    );

    const doc = new PDFDocument({ margin: 50 });
    doc.pipe(res);

    addHeader(doc, "Security Deposit Statement");

    addField(doc, "Property", deposit.property_name);
    addField(doc, "Address", `${deposit.address}, ${deposit.city}`);
    addField(doc, "Tenant", deposit.tenant_name);
    addField(doc, "Lease ID", deposit.lease_id);
    addField(doc, "Lease Period", `${deposit.start_date} to ${deposit.end_date}`);

    doc.moveDown();
    doc.fontSize(13).font("Helvetica-Bold").text("Deposit Breakdown");
    doc.moveDown();

    addField(doc, "Initial Deposit", `INR ${deposit.initial_amount}`);
    addField(doc, "Total Deductions", `INR ${deposit.deduction_amount}`);
    addField(doc, "Refund Amount", `INR ${deposit.refund_amount}`);
    addField(doc, "Settlement Status", deposit.status);

    doc.moveDown(2);
    doc.fontSize(9).text(
      "This statement is generated from the records maintained in RentSure.",
      { align: "center" }
    );

    doc.end();

  } catch (error) {
    console.error("Deposit PDF error:", error.message);
    if (!res.headersSent) {
      res.status(500).json({
        success: false,
        message: "Could not generate deposit PDF."
      });
    } else {
      res.destroy(error);
    }
  }
};

module.exports = {
  generateInspectionReport,
  generateDepositReport
};